if (!UnityEngine.Application.isPlaying) return "Play mode required";
var player = UnityEngine.Object.FindFirstObjectByType<Shinzui.View.PlayerView>();
var camera = UnityEngine.Camera.main;
var asset = UnityEditor.AssetDatabase.LoadAssetAtPath<UnityEngine.GameObject>("Assets/Shinzui/Prefabs/StonePrefab.prefab");
var stone = UnityEngine.Object.Instantiate(asset);
stone.name = "PickupProbeStone";
foreach (var rb in stone.GetComponentsInChildren<UnityEngine.Rigidbody>()) rb.isKinematic = true;
var target = stone.GetComponent<Shinzui.View.Interaction.InteractableComponent>();
stone.transform.position += camera.transform.position + camera.transform.forward * .35f - target.PickupPosition;
var effect = stone.AddComponent<Shinzui.View.Interaction.PickupInterruptionView>();
var so = new UnityEditor.SerializedObject(effect);
so.FindProperty("waitForResume").boolValue = true;
so.ApplyModifiedPropertiesWithoutUndo();
UnityEngine.Physics.SyncTransforms();
var view = UnityEngine.Object.FindFirstObjectByType<Shinzui.View.Interaction.PlayerInteractionView>();
var scope = UnityEngine.Object.FindFirstObjectByType<Shinzui.DI.PlayerLifetimeScope>();
var input = (Shinzui.Application.Interfaces.IInputService)scope.Container.Resolve(typeof(Shinzui.Application.Interfaces.IInputService));
var body = player.GetComponentInChildren<Shinzui.View.PlayerBodyView>();
var shoulder = body.GetComponentsInChildren<UnityEngine.Transform>().First(t=>t.name=="RightUpperArm");
return Newtonsoft.Json.JsonConvert.SerializeObject(new { frame=UnityEngine.Time.frameCount, target=target.PickupPosition.ToString(), shoulder=shoulder.position.ToString(), reach=body.CanReachPickup(target.PickupPosition), valid=view.CanContinuePickup(target), held=input.ItemUseHeld });
